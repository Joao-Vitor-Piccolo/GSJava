CREATE TABLE MORADOR (
    ID_MORADOR NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    TELEFONE VARCHAR2(20) NOT NULL,
    RUA VARCHAR2(120) NOT NULL,
    NUMERO VARCHAR2(20) NOT NULL,
    QUARTEIRAO VARCHAR2(80) NOT NULL
);

CREATE TABLE RELATO (
    ID_RELATO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FK_MORADOR NUMBER NOT NULL,
    TIPO VARCHAR2(80) NOT NULL,
    LOCAL VARCHAR2(150) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_RELATO_MORADOR FOREIGN KEY (FK_MORADOR) REFERENCES MORADOR (ID_MORADOR)
);

CREATE TABLE LEITURA (
    ID_LEITURA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CODIGO_SENTINELA VARCHAR2(40) NOT NULL,
    OVOS NUMBER NOT NULL,
    NIVEL_AGUA NUMBER NOT NULL,
    TEMPERATURA NUMBER NOT NULL,
    UMIDADE NUMBER NOT NULL,
    DATA_HORA TIMESTAMP NOT NULL
);
